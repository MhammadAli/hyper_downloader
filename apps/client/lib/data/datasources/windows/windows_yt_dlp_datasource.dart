  List<String> buildInstagramNetworkArgs(List<String> baseArgs) {
    final args = <String>[
      '--socket-timeout',
      instagramSocketTimeoutSecs,
    ];
    final pluginDir = ensureInstagramPluginDir();
    if (pluginDir != null) {
      args.addAll(['--no-plugin-dirs', '--plugin-dirs', pluginDir]);
    }
    args.addAll(baseArgs);
    return args;
  }

  List<String> buildDownloadArgs(
    WindowsToolPaths paths,
    StartDownloadRequest request,
    String validatedUrl,
    String outputTemplate,
  ) {
    final common = _buildDownloadCommonArgs(paths, request, outputTemplate);
    return [...common, '--', validatedUrl];
  }

  List<String> buildDownloadArgsFromInfoJson(
    WindowsToolPaths paths,
    StartDownloadRequest request,
    String outputTemplate,
    String infoJsonPath, {
    bool isInstagram = false,
    bool useMetaNetworkArgs = false,
  }) {
    final common = _buildDownloadCommonArgs(paths, request, outputTemplate);
    if (isInstagram || useMetaNetworkArgs) {
      final pluginDir = ensureInstagramPluginDir();
      final prefix = <String>['--socket-timeout', instagramSocketTimeoutSecs];
      if (pluginDir != null) {
        prefix.addAll(['--no-plugin-dirs', '--plugin-dirs', pluginDir]);
      }
      common.insertAll(0, prefix);
    }
    common.addAll(['--load-info-json', infoJsonPath]);
    return common;
  }

  List<String> _buildDownloadCommonArgs(
    WindowsToolPaths paths,
    StartDownloadRequest request,
    String outputTemplate,
  ) {
    final String formatExpr;
    String? mergeContainer;
    switch (request.selection.kind) {
      case DownloadSelectionKind.single:
        final trimmed = request.selection.formatId?.trim() ?? '';
        _validateFormatId(trimmed, 'format_id');
        formatExpr = trimmed;
      case DownloadSelectionKind.videoAndAudio:
        final video = request.selection.videoFormatId?.trim() ?? '';
        final audio = request.selection.audioFormatId?.trim() ?? '';
        _validateFormatId(video, 'video_format_id');
        _validateFormatId(audio, 'audio_format_id');
        final rawContainer = request.selection.mergeContainer?.trim();
        final container = (rawContainer != null && rawContainer.isNotEmpty)
            ? rawContainer
            : 'mp4';
        _validateFormatId(container, 'merge_container');
        formatExpr = '$video+$audio';
        mergeContainer = container;
    }

    final args = <String>[
      '--newline',
      '--continue',
      '--no-playlist',
      '--no-mtime',
      '--ignore-config',
      '--encoding',
      'utf-8',
      '--js-runtimes',
      'node:${paths.nodeExe}',
      '--ffmpeg-location',
      paths.ffmpegDir,
      '--progress-template',
      downloadProgressTemplate,
      '--progress-template',
      postprocessProgressTemplate,
      '-f',
      formatExpr,
    ];

    if (mergeContainer != null) {
      args.addAll(['--merge-output-format', mergeContainer]);
    }
    args.addAll(['-o', outputTemplate]);
    return args;
  }

  static void _validateFormatId(String value, String fieldName) {
    if (value.isEmpty) {
      throw ParseException('$fieldName cannot be empty.');
    }
    if (RegExp(r'[\s\x00-\x1F\x7F]').hasMatch(value)) {
      throw ParseException(
        '$fieldName contains invalid whitespace or control characters.',
      );
    }
  }

  Future<YtDlpCommandResult> runInspectionCommand(
    WindowsToolPaths paths,
    List<String> args, {
    Duration? timeout,
    Future<void>? cancelSignal,
  }) async {
    final process = await Process.start(
      paths.ytDlpExe,
      args,
      runInShell: false,
      environment: _utf8Env,
    );
    final treeHandle = ProcessTreeHandle.attach(process);
    final stdoutBuf = StringBuffer();
    final stderrBuf = StringBuffer();

    final stdoutSub = process.stdout
        .transform(const Utf8Decoder(allowMalformed: true))
        .listen(stdoutBuf.write);
    final stderrSub = process.stderr
        .transform(const Utf8Decoder(allowMalformed: true))
        .listen(stderrBuf.write);

    var timedOut = false;
    var canceled = false;
    Timer? timer;

    if (timeout != null) {
      timer = Timer(timeout, () {
        timedOut = true;
        unawaited(treeHandle.terminate());
      });
    }
    if (cancelSignal != null) {
      unawaited(
        cancelSignal.then((_) {
          if (!timedOut) {
            canceled = true;
            unawaited(treeHandle.terminate());
          }
        }),
      );
    }

    final exitCode = await process.exitCode;
    timer?.cancel();
    await Future.wait([stdoutSub.cancel(), stderrSub.cancel()]);
    treeHandle.close();

    if (canceled) {
      throw const ProcessExecutionException('Stopped by user');
    }

    var stderrText = stderrBuf.toString().trim();
    if (timedOut) {
      stderrText = stderrText.isEmpty
          ? 'Timed out while connecting during media analysis.'
          : '$stderrText\nTimed out while connecting during media analysis.';
    }

    return YtDlpCommandResult(
      exitCode: exitCode,
      stdout: stdoutBuf.toString(),
      stderr: stderrText,
      timedOut: timedOut,
    );
  }

  Future<YtDlpDownloadAttemptResult> runDownloadAttempt({
    required String jobId,
    required WindowsToolPaths paths,
    required List<String> args,
    required bool Function() isCancelRequested,
    required Future<void> cancelSignal,
    required void Function(ProcessTreeHandle handle) onProcessAttached,
    required void Function() onProcessDetached,
    required void Function(ParsedYtDlpLine line) onParsedLine,
    Duration? firstByteTimeout,
  }) async {
    final sep = Platform.pathSeparator;
    final pathRecordFile = File(
      '${Directory.systemTemp.path}${sep}hyperdl_path_$jobId.txt',
    );
    if (await pathRecordFile.exists()) {
      try {
        await pathRecordFile.delete();
      } catch (_) {}
    }

    final fullArgs = <String>[
      '--no-quiet',
      '--print-to-file',
      'after_move:%(filepath)s',
      pathRecordFile.path,
      ...args,
    ];

    final Process process;
    try {
      process = await Process.start(
        paths.ytDlpExe,
        fullArgs,
        runInShell: false,
        environment: _utf8Env,
      );
    } catch (err) {
      try {
        if (await pathRecordFile.exists()) await pathRecordFile.delete();
      } catch (_) {}
      return YtDlpDownloadAttemptResult(
        stderrText: '',
        lastDownloaded: 0,
        lastEstimated: false,
        timedOut: false,
        launchError: err,
      );
    }

    final treeHandle = ProcessTreeHandle.attach(process);
    onProcessAttached(treeHandle);
    if (isCancelRequested()) {
      await treeHandle.terminate();
    }

    final stderrLines = <String>[];
    final stderrDone = process.stderr
        .transform(const Utf8Decoder(allowMalformed: true))
        .transform(const LineSplitter())
        .listen(stderrLines.add)
        .asFuture<void>();

    var lastDownloaded = 0;
    int? lastTotal;
    var lastEstimated = false;
    String? detectedOutputPath;
    var receivedFirstByte = false;
    var timedOut = false;

    Timer? firstByteTimer;
    if (firstByteTimeout != null) {
      firstByteTimer = Timer(firstByteTimeout, () {
        if (!receivedFirstByte) {
          timedOut = true;
          unawaited(treeHandle.terminate());
        }
      });
    }

    unawaited(
      cancelSignal.then((_) {
        unawaited(treeHandle.terminate());
      }),
    );

    final stdoutDone = process.stdout
        .transform(const Utf8Decoder(allowMalformed: true))
        .transform(const LineSplitter())
        .listen((rawLine) {
          if (isCancelRequested()) return;
          final parsed = YtDlpProgressParser.parseLine(rawLine);
          if (parsed is ParsedDownloadProgress) {
            if (parsed.totalBytes != null) {
              lastTotal = parsed.totalBytes;
              lastEstimated = parsed.isTotalEstimated;
            }
            if (parsed.downloadedBytes > 0 || parsed.status == 'finished') {
              if (!receivedFirstByte) {
                receivedFirstByte = true;
                firstByteTimer?.cancel();
              }
              lastDownloaded = parsed.downloadedBytes > 0
                  ? parsed.downloadedBytes
                  : (lastTotal ?? lastDownloaded);
            }
          } else if (parsed is ParsedOutputPathDetected) {
            detectedOutputPath = parsed.path;
          }
          onParsedLine(parsed);
        })
        .asFuture<void>();

    final exitCode = await process.exitCode;
    firstByteTimer?.cancel();
    onProcessDetached();
    treeHandle.close();

    await Future.wait([
      stdoutDone.catchError((_) {}),
      stderrDone.catchError((_) {}),
    ]);

    var stderrText = stderrLines.join('\n');
    if (timedOut) {
      const marker =
          'Timed out while connecting before media transfer started.';
      stderrText = stderrText.isEmpty ? marker : '$stderrText\n$marker';
    }

    String? recordedOutputPath;
    try {
      if (await pathRecordFile.exists()) {
        final content = utf8.decode(
          await pathRecordFile.readAsBytes(),
          allowMalformed: true,
        );
        for (final line in content.split(RegExp(r'\r?\n')).reversed) {
          final t = line.trim();
          if (t.isNotEmpty) {
            recordedOutputPath = t;
            break;
          }
        }
        await pathRecordFile.delete();
      }
    } catch (_) {}

    return YtDlpDownloadAttemptResult(
      exitCode: exitCode,
      stderrText: stderrText,
      recordedOutputPath: recordedOutputPath,
      detectedOutputPath: detectedOutputPath,
      lastDownloaded: lastDownloaded,
      lastTotal: lastTotal,
      lastEstimated: lastEstimated,
      timedOut: timedOut,
    );
  }

  /// Removes incomplete `*.temp.*` mux artifacts while preserving `.part`/`.ytdl` files.
  Future<void> cleanupTempMuxArtifacts(
    String outputTemplate,
    DateTime since,
  ) async {
    final parent = File(outputTemplate).parent;
    if (!await parent.exists()) return;

    final fileName = outputTemplate.replaceAll('\\', '/').split('/').last;
    final stemCandidate = fileName
        .split('%(')
        .first
        .replaceAll(RegExp(r'\.+$'), '')
        .toLowerCase();
    final stemPrefix = stemCandidate.isNotEmpty ? stemCandidate : null;

    await for (final entity in parent.list(followLinks: false)) {
      if (entity is! File) continue;
      final nameLower = entity.uri.pathSegments.last.toLowerCase();
      if (!nameLower.contains('.temp.') ||
          nameLower.endsWith('.part') ||
          nameLower.endsWith('.ytdl')) {
        continue;
      }
      if (stemPrefix != null) {
        if (!nameLower.startsWith(stemPrefix)) continue;
      } else {
        try {
          final stat = await entity.stat();
          if (stat.modified.isBefore(since)) continue;
        } catch (_) {}
      }
      try {
        await entity.delete();
      } catch (_) {}
    }
  }

  String resolveOutputTemplateForNewJob(
    Directory outputDir,
    StartDownloadRequest request, {
    String? shortcode,
  }) {
    String? formatTag;
    if (request.selection.kind == DownloadSelectionKind.single) {
      final f = request.selection.formatId?.trim();
      if (f != null && f.isNotEmpty) {
        formatTag = FilenameSanitizer.sanitizeWindowsFilename(f, 48);
      }
    } else {
      final v = request.selection.videoFormatId?.trim();
      final a = request.selection.audioFormatId?.trim();
      if (v != null && v.isNotEmpty && a != null && a.isNotEmpty) {
        formatTag = FilenameSanitizer.sanitizeWindowsFilename('$v+$a', 64);
      }
    }

    final sep = Platform.pathSeparator;
    final title = request.title?.trim();
    final code = shortcode?.trim();
    if (title != null &&
        title.isNotEmpty &&
        code != null &&
        code.isNotEmpty &&
        formatTag != null) {
      final safeTitle = FilenameSanitizer.sanitizeWindowsFilename(title, 60);
      final safeCode = FilenameSanitizer.sanitizeWindowsFilename(code, 48);
      final baseStem = '$safeTitle [$safeCode] [$formatTag]';
      final uniqueStem = _pickNonCollidingStem(outputDir, baseStem);
      return '${outputDir.path}$sep$uniqueStem.%(ext)s';
    }

    return '${outputDir.path}$sep%(title).60B [%(id)s] [%(format_id)s].%(ext)s';
  }

  static String _pickNonCollidingStem(Directory outputDir, String baseStem) {
    if (!_stemHasCompletedFile(outputDir, baseStem)) return baseStem;
    for (var idx = 2; idx <= 10000; idx++) {
      final candidate = '$baseStem ($idx)';
      if (!_stemHasCompletedFile(outputDir, candidate)) return candidate;
    }
    return '$baseStem (${DateTime.now().microsecondsSinceEpoch})';
  }

  static bool _stemHasCompletedFile(Directory outputDir, String stem) {
    if (!outputDir.existsSync()) return false;
    final prefix = '$stem.'.toLowerCase();
    for (final entity in outputDir.listSync(followLinks: false)) {
      if (entity is! File) continue;
      final nameLower = entity.uri.pathSegments.last.toLowerCase();
      if (nameLower.startsWith(prefix) &&
          !nameLower.endsWith('.part') &&
          !nameLower.endsWith('.ytdl') &&
          !nameLower.contains('.temp.')) {
        return true;
      }
    }
    return false;
  }

  static String? sanitizeInfoJsonForReuse(String rawJson) {
    try {
      final decoded = jsonDecode(rawJson);
      if (decoded is! Map) return null;
      final obj = Map<String, dynamic>.from(decoded);
      for (final key in const [
        'requested_formats',
        'requested_downloads',
        'format_id',
        'format',
        'ext',
        '_filename',
        'filename',
      ]) {
        obj.remove(key);
      }
      return jsonEncode(obj);
    } catch (_) {
      return null;
    }
  }
