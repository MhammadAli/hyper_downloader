class YtDlpCommandResult {
  final int exitCode;
  final String stdout;
  final String stderr;
  final bool timedOut;

  const YtDlpCommandResult({
    required this.exitCode,
    required this.stdout,
    required this.stderr,
    required this.timedOut,
  });

  bool get succeeded => !timedOut && exitCode == 0;
}

class YtDlpDownloadAttemptResult {
  final int? exitCode;
  final String stderrText;
  final String? recordedOutputPath;
  final String? detectedOutputPath;
  final int lastDownloaded;
  final int? lastTotal;
  final bool lastEstimated;
  final bool timedOut;
  final Object? launchError;

  const YtDlpDownloadAttemptResult({
    this.exitCode,
    required this.stderrText,
    this.recordedOutputPath,
    this.detectedOutputPath,
    required this.lastDownloaded,
    this.lastTotal,
    required this.lastEstimated,
    required this.timedOut,
    this.launchError,
  });

  bool get succeeded =>
      launchError == null && !timedOut && exitCode != null && exitCode == 0;
}

/// Executes `yt-dlp.exe` out-of-process on Windows with UTF-8 environment,
/// Win32 Job Object process-tree cleanup, Instagram DNS/ECH helper plugin,
/// and structured progress line callbacks.
class WindowsYtDlpDataSource {
  static const String downloadProgressTemplate =
      'download:HYPERDL|%(progress.status)s|%(progress.downloaded_bytes)s|%(progress.total_bytes)s|%(progress.total_bytes_estimate)s|%(progress.speed)s|%(progress.eta)s';
  static const String postprocessProgressTemplate =
      'postprocess:HYPERDL_PP|%(progress.status)s|%(progress.postprocessor)s';
  static const String instagramSocketTimeoutSecs = '40';

  static const String _instagramDnsPluginPy = r'''# Auto-generated by HyperDownload for Windows Instagram CurlCFFIRH DNS/ECH speed.
import ipaddress
import socket
import urllib.parse

from curl_cffi.const import CurlOpt
from yt_dlp.networking import _curlcffi

_DNS_CACHE = {}


def _resolve_ipv4_os(host, port):
    key = (host, port)
    if key in _DNS_CACHE:
        return _DNS_CACHE[key]
    try:
        infos = socket.getaddrinfo(host, port, socket.AF_INET, socket.SOCK_STREAM)
        ips = []
        for info in infos:
            ip = info[4][0]
            if ip not in ips:
                ips.append(ip)
        _DNS_CACHE[key] = ips
        return ips
    except OSError:
        _DNS_CACHE[key] = []
        return []


def _is_ip_literal(host):
    try:
        ipaddress.ip_address(host)
        return True
    except ValueError:
        return False


if not getattr(_curlcffi.CurlCFFIRH, "_hyperdl_ig_dns_patched", False):
    _orig_send = _curlcffi.CurlCFFIRH._send

    def _hyperdl_fast_dns_send(self, request):
        try:
            session = self._get_instance(
                cookiejar=self._get_cookiejar(request) if "cookie" not in request.headers else None
            )
            opts = dict(getattr(session, "curl_options", None) or {})
            ech_opt = getattr(CurlOpt, "ECH", None)
            if ech_opt is not None:
                opts[ech_opt] = "grease"

            proxies = self._get_proxies(request)
            has_proxy = bool({k: v for k, v in proxies.items() if k != "no" and v})
            if not has_proxy:
                parsed = urllib.parse.urlparse(request.url)
                host = parsed.hostname
                port = parsed.port or (443 if parsed.scheme == "https" else 80)
                resolve_opt = getattr(CurlOpt, "RESOLVE", None)
                ipresolve_opt = getattr(CurlOpt, "IPRESOLVE", None)
                if host and not _is_ip_literal(host) and resolve_opt is not None:
                    ips = _resolve_ipv4_os(host, port)
                    if ips:
                        existing = [
                            item
                            for item in list(opts.get(resolve_opt, []))
                            if not str(item).startswith(f"{host}:{port}:")
                        ]
                        existing.append(f"{host}:{port}:{','.join(ips)}")
                        opts[resolve_opt] = existing
                        if ipresolve_opt is not None:
                            opts[ipresolve_opt] = 1
            session.curl_options = opts
        except Exception:
            pass
        return _orig_send(self, request)

    _curlcffi.CurlCFFIRH._send = _hyperdl_fast_dns_send
    _curlcffi.CurlCFFIRH._hyperdl_ig_dns_patched = True
''';

  String? _verifiedPluginRoot;

  static const Map<String, String> _utf8Env = {
    'PYTHONUTF8': '1',
    'PYTHONIOENCODING': 'utf-8',
  };

  WindowsToolPaths resolveToolPaths() => WindowsToolPaths.resolve();

  String? ensureInstagramPluginDir() {
    if (_verifiedPluginRoot != null) return _verifiedPluginRoot;
    try {
      final sep = Platform.pathSeparator;
      final root = Directory(
        '${Directory.systemTemp.path}${sep}hyperdl_ytdlp_plugins_v1',
      );
      final extractorDir = Directory(
        '${root.path}${sep}hyperdl_ig_dns${sep}yt_dlp_plugins${sep}extractor',
      );
      final pluginFile = File('${extractorDir.path}${sep}hyperdl_ig_dns.py');
      if (pluginFile.existsSync() &&
          pluginFile.readAsStringSync() == _instagramDnsPluginPy) {
        _verifiedPluginRoot = root.path;
        return _verifiedPluginRoot;
      }
      extractorDir.createSync(recursive: true);
      final tempFile = File(
        '${extractorDir.path}${sep}hyperdl_ig_dns.${DateTime.now().microsecondsSinceEpoch}.tmp',
      );
      tempFile.writeAsStringSync(_instagramDnsPluginPy, flush: true);
      try {
        tempFile.renameSync(pluginFile.path);
      } catch (_) {
        try {
          tempFile.deleteSync();
        } catch (_) {}
        pluginFile.writeAsStringSync(_instagramDnsPluginPy, flush: true);
      }
      _verifiedPluginRoot = root.path;
      return _verifiedPluginRoot;
    } catch (_) {
      return null;
    }
  }

